"""Deterministic extract of the norm text (#law-content) from the saved leis.org page.

Usage: python -m aneel_rag.ingest.extract_law_content [full_html] [extract_html]
"""

import sys
from pathlib import Path

from bs4 import BeautifulSoup, Comment, Tag

from aneel_rag.config.settings import PROJECT_ROOT, file_sha256

RAW = PROJECT_ROOT / "data" / "raw"
DEFAULT_SOURCE = RAW / "ren1000.html"
DEFAULT_TARGET = RAW / "ren1000_law_content.html"

# UI chrome inside the norm container: related-norms list (with leaked SQL) and download buttons.
DROP_SELECTORS = ["#extras", "[data-extra-below-epigrafe]", "script", "style", "button", "svg"]
KEEP_CLASSES = {"artigo", "titulo", "link_law", "table-wrapper", "figura"}
KEEP_ATTRS = {"data-summary-id", "data-summary-type", "data-original-title", "data-file"}


def _clean_attrs(tag: Tag) -> None:
    classes = [c for c in tag.get("class", []) if c in KEEP_CLASSES]
    attrs = {k: v for k, v in tag.attrs.items() if k in KEEP_ATTRS}
    if tag.name == "a" and "link_law" in classes and tag.get("href", "#") != "#":
        attrs["href"] = tag["href"]
    if classes:
        attrs["class"] = classes
    tag.attrs = attrs


def extract(html: bytes, source_sha: str) -> str:
    soup = BeautifulSoup(html, "lxml")
    content = soup.select_one("div.aneel-content")
    if content is None:
        raise ValueError("div.aneel-content not found; is this the leis.org page?")
    for selector in DROP_SELECTORS:
        for node in content.select(selector):
            node.decompose()
    for comment in content.find_all(string=lambda s: isinstance(s, Comment)):
        comment.extract()
    for img in content.find_all("img"):
        name = Path(img.get("src", "")).name
        marker = soup.new_tag("span", attrs={"class": "figura", "data-file": name})
        marker.string = f"[FIGURA: {name}]"
        img.replace_with(marker)
    for tag in content.find_all(True):
        _clean_attrs(tag)
    content.attrs = {"class": ["aneel-content"]}

    body = str(content)
    if "SELECT " in body:
        raise ValueError("template SQL leaked into the extract")
    # One line per <br/> keeps git diffs readable; whitespace is collapsed at parse time.
    body = "\n".join(line.rstrip() for line in body.replace("<br/>", "<br/>\n").splitlines())
    header = (
        "<!-- Generated by `python -m aneel_rag.ingest.extract_law_content` from ren1000.html "
        f"(sha256 {source_sha}). Do not edit by hand. -->"
    )
    return f"{header}\n{body}\n"


def main(argv: list[str]) -> None:
    source = Path(argv[0]) if argv else DEFAULT_SOURCE
    target = Path(argv[1]) if len(argv) > 1 else DEFAULT_TARGET
    text = extract(source.read_bytes(), file_sha256(source))
    target.write_bytes(text.encode("utf-8"))
    print(f"wrote {target} ({len(text):,} chars, sha256 {file_sha256(target)})")


if __name__ == "__main__":
    main(sys.argv[1:])
